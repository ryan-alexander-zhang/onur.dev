// QuickAdd loads a single script; regenerate these bundles after editing the library.
const fs = require('node:fs')
const path = require('node:path')
const directory = path.join(__dirname, 'quickadd')
const source = fs.readFileSync(path.join(directory, 'contentful-sync-lib.js'), 'utf8')
for (const [name, mode] of [
  ['contentful-publish-current-note.js', 'publish'],
  ['contentful-sync-preview-current-note.js', 'preview']
]) {
  const output = `${source}\n// Generated by scripts/obsidian/generate-quickadd.cjs\nmodule.exports = createQuickAddModule('${mode}')\n`
  const target = path.join(directory, name)
  if (process.argv.includes('--check')) {
    if (fs.readFileSync(target, 'utf8') !== output) throw new Error(`Stale QuickAdd bundle: ${name}`)
  } else fs.writeFileSync(target, output)
}
